    // Relationships
    public function creator()
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    public function pos_system()
    {
        return $this->belongsTo(PosModel::class, 'pos_id', 'id');
    }
    public function updater()
    {
        return $this->belongsTo(User::class, 'updated_by');
    }

    public function payment()
    {
        return $this->hasMany(Payment::class, 'payment_summury_id', 'id');
    }

    public function ensureGeneratedPaymentEntry(): ?Payment
    {
        return DB::transaction(function () {
            $summary = self::whereKey($this->getKey())->lockForUpdate()->firstOrFail();
            $entry = $summary->payment()->where('remark', 'Auto Generated')->first();
            if ($entry) {
                return $entry;
            }

            if (!self::createAutoGeneratedPayment($summary)) {
                return null;
            }

            return $summary->payment()->where('remark', 'Auto Generated')->first();
        });
    }

    public static function store_summary($data)
    {
        // DB::beginTransaction();
        try {
            $existing = self::where('date', $data['date'])
                ->where('pos_id', $data['pos_id'])
                ->lockForUpdate()
                ->first();

            if ($existing) {
                $hasAutoGeneratedPayment = Payment::where('payment_summury_id', $existing->id)
                    ->where('remark', 'Auto Generated')
                    ->exists();

                if ($hasAutoGeneratedPayment) {
                    DB::commit();
                    return 1;
                }

                if (! self::createAutoGeneratedPayment($existing)) {
                    DB::rollBack();
                    return 3;
                }

                DB::commit();
                return 4;
            }

            $res = self::create([
                'pos_id' => $data['pos_id'],
                'date'                 => $data['date'],
                'total_transaction'    => $data['total_transactions'],
                'total_billing_amount' => $data['billing_amount'],
                'by_cash'              => $data['cash_upi'] ?? $data['payByCashOrUpi'],
                'by_wallet'            => $data['wallet'] ?? $data['payByWallet'],
                'by_reward'            => $data['reward'] ?? $data['payByReward'],
                'pos_credit'           => $data['credit_amount'] ?? $data['creditAmount'],
                'pos_debit'            => $data['debit_amount'] ?? $data['debitAmount'],
                'admin_credit'         => $data['debit_amount'] ?? $data['debitAmount'],
                'admin_debit'          => $data['credit_amount'] ?? $data['creditAmount'],
                'status'               => 'pending',
                'created_by'           => null,
                // 'updated_by' => auth()->user()->id,
            ]);

            if (! $res || ! self::createAutoGeneratedPayment($res)) {
                DB::rollBack();
                return 3;
            }

            DB::commit();
            return 2;
        } catch (\Throwable $e) {
            DB::rollBack();
            Log::info('Summary Creation Error: ' . $e->getMessage());
            Log::info('File: ' . $e->getFile());
            Log::info('Line: ' . $e->getLine());
            return false;
        }
    }

    private static function createAutoGeneratedPayment(self $summary): bool
    {
        $posUserId = $summary->pos_system()->value('user_id');
        if (! $posUserId) {
            return false;
        }

        $voucherNumber = Helper::generateVoucherNumber();
        $amount = $summary->admin_credit > 0
            ? $summary->admin_credit
            : $summary->admin_debit;

        return Payment::insert([
            'payment_summury_id' => $summary->id,
            'transaction_date' => $summary->date,
            'voucher_number' => $voucherNumber,
            'reference_number' => 'atcrt' . $voucherNumber,
            'account_details' => null,
            'pay_by' => null,
            'amount' => $amount,
            'to' => $summary->pos_credit > 0 ? $posUserId : 666666,
            'from' => $summary->pos_credit > 0 ? 666666 : $posUserId,
            'created_by' => 666666,
            'updated_by' => 666666,
            'remark' => 'Auto Generated',
            'created_at' => now(),
            'updated_at' => now(),
        ]);
    }

    public static function fetch_summary_pos()
    {
        $user_id = auth()->user()->user_id;
        $pos_id = Helper::get_pos_id($user_id);
        $resp = self::with('statusChanges')->where('pos_id', $pos_id)->orderBy('id', 'desc')->get()->map(function ($item) {
            $item->intiate_date = Carbon::parse($item->date)->format('d-m-Y');
            return $item;
        });
        return $resp;
    }

